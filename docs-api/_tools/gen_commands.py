# ── reading the EMStudio tree ───────────────────────────────────────────────

class Tree:
    """EMStudio's files, at HEAD (default) or on disk."""

    def __init__(self, root: Path, worktree: bool):
        self.root = root
        self.sha = self._git("rev-parse", "--short", "HEAD")
        self.at_head = bool(self.sha) and not worktree
        self._cache: Dict[str, Optional[str]] = {}

    def _git(self, *args: str) -> str:
        try:
            out = subprocess.run(["git", "-C", str(self.root), *args], capture_output=True, check=True)
            return out.stdout.decode("utf-8", "replace").strip()
        except (OSError, subprocess.CalledProcessError):
            return ""

    def read(self, rel: str) -> Optional[str]:
        if rel not in self._cache:
            text: Optional[str] = None
            if self.at_head:
                try:
                    out = subprocess.run(["git", "-C", str(self.root), "show", f"HEAD:{rel}"],
                                         capture_output=True, check=True)
                    text = out.stdout.decode("utf-8")
                except (OSError, subprocess.CalledProcessError):
                    text = None
            else:
                p = self.root / rel
                text = p.read_text(encoding="utf-8") if p.is_file() else None
            self._cache[rel] = text
        return self._cache[rel]


def line_of(text: Optional[str], pattern: str, flags: int = 0) -> Optional[int]:
    if not text:
        return None
    m = re.search(pattern, text, flags | re.M)
    return text.count("\n", 0, m.start()) + 1 if m else None


# ── a tiny parser for the JS literals of the tables ─────────────────────────

_TOKEN = re.compile(r"""
    (?P<ws>\s+)
  | (?P<lc>//[^\n]*)
  | (?P<bc>/\*.*?\*/)
  | (?P<str>"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'|`(?:\\.|[^`\\])*`)
  | (?P<num>-?\d+(?:\.\d+)?)
  | (?P<id>[A-Za-z_$][\w$]*)
  | (?P<punct>\.\.\.|=>|[{}\[\]():,+?|<>=.;!&*/-])
""", re.X | re.S)

_ESC = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f", "v": "\v", "0": "\0"}


def js_unquote(lit: str) -> str:
    body, out, i = lit[1:-1], [], 0
    while i < len(body):
        c = body[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        i += 1
        if i >= len(body):
            break
        c = body[i]
        if c == "u":
            if body[i + 1:i + 2] == "{":
                j = body.index("}", i)
                out.append(chr(int(body[i + 2:j], 16)))
                i = j + 1
            else:
                out.append(chr(int(body[i + 1:i + 5], 16)))
                i += 5
            continue
        if c == "x":
            out.append(chr(int(body[i + 1:i + 3], 16)))
            i += 3
            continue
        if c == "\n":
            i += 1
            continue
        out.append(_ESC.get(c, c))
        i += 1
    return "".join(out)


def tokenize(src: str) -> List[Tuple[str, str]]:
    toks, pos = [], 0
    while pos < len(src):
        m = _TOKEN.match(src, pos)
        if not m:
            toks.append(("other", src[pos]))
            pos += 1
            continue
        pos = m.end()
        kind = m.lastgroup
        if kind in ("ws", "lc", "bc"):
            continue
        toks.append((kind, m.group()))
    return toks


class Call(dict):
    """``name(args)`` as found in the source."""


class Ref(str):
    """An identifier not resolved (kept by name)."""


class LiteralParser:
    def __init__(self, toks: List[Tuple[str, str]], env: Optional[Dict[str, Any]] = None):
        self.t, self.i, self.env = toks, 0, env or {}

    def peek(self, k: int = 0) -> Tuple[str, str]:
        j = self.i + k
        return self.t[j] if j < len(self.t) else ("eof", "")

    def take(self, value: Optional[str] = None) -> Tuple[str, str]:
        tok = self.peek()
        if value is not None and tok[1] != value:
            raise ValueError(f"expected {value!r}, got {tok[1]!r} at token {self.i}")
        self.i += 1
        return tok

    def expr(self) -> Any:
        v = self.primary()
        while True:
            kind, val = self.peek()
            if val == "+":
                self.take()
                rhs = self.primary()
                v = f"{v}{rhs}" if isinstance(v, str) and isinstance(rhs, str) else v
            elif kind == "id" and val in ("as", "satisfies"):
                self.take()
                self.skip_type()
            else:
                return v

    def skip_type(self) -> None:
        self.take()
        while self.peek()[1] in ("[", "<", "|", "."):
            if self.peek()[1] == "[":
                self.take("[")
                self.take("]")
            elif self.peek()[1] == "<":
                depth = 0
                while True:
                    _, v = self.take()
                    depth += (v == "<") - (v == ">")
                    if depth == 0:
                        break
            else:
                self.take()
                self.take()

    def primary(self) -> Any:
        kind, val = self.peek()
        if kind == "str":
            self.take()
            return js_unquote(val)
        if kind == "num":
            self.take()
            return float(val) if "." in val else int(val)
        if val == "{":
            return self.obj()
        if val == "[":
            return self.arr()
        if val == "(":
            self.take("(")
            v = self.expr()
            self.take(")")
            return v
        if kind == "id":
            self.take()
            if val in ("true", "false"):
                return val == "true"
            if val in ("null", "undefined"):
                return None
            if self.peek()[1] == "(":
                self.take("(")
                args = []
                while self.peek()[1] != ")":
                    args.append(self.expr())
                    if self.peek()[1] == ",":
                        self.take()
                self.take(")")
                c = Call(name=val, args=args)
                return c
            return self.env.get(val, Ref(val))
        raise ValueError(f"unexpected token {val!r} at {self.i}")

    def arr(self) -> List[Any]:
        self.take("[")
        out: List[Any] = []
        while self.peek()[1] != "]":
            if self.peek()[1] == "...":
                self.take()
                v = self.expr()
                out.extend(v if isinstance(v, list) else [])
            else:
                out.append(self.expr())
            if self.peek()[1] == ",":
                self.take()
        self.take("]")
        return out

    def obj(self) -> Dict[str, Any]:
        self.take("{")
        out: Dict[str, Any] = {}
        while self.peek()[1] != "}":
            if self.peek()[1] == "...":
                self.take()
                v = self.expr()
                if isinstance(v, dict):
                    out.update(v)
            else:
                kind, key = self.take()
                key = js_unquote(key) if kind == "str" else key
                if self.peek()[1] == ":":
                    self.take(":")
                    out[key] = self.expr()
                else:                       # shorthand `{ id }`
                    out[key] = self.env.get(key, Ref(key))
            if self.peek()[1] == ",":
                self.take()
        self.take("}")
        return out


def const_literal(src: str, name: str, env: Optional[Dict[str, Any]] = None) -> Any:
    """The value of ``const <name>[: Type] = <literal>`` in ``src``."""
    m = re.search(rf"\bconst\s+{re.escape(name)}\b[^=]*=\s*", src)
    if not m:
        raise LookupError(name)
    p = LiteralParser(tokenize(src[m.end():m.end() + _literal_span(src, m.end())]), env)
    return p.expr()


def _literal_span(src: str, start: int) -> int:
    """Length of the bracketed literal starting at ``start`` (strings and comments aware)."""
    depth, i, n = 0, start, len(src)
    while i < n:
        m = _TOKEN.match(src, i)
        if not m:
            i += 1
            continue
        tok = m.group()
        if m.lastgroup == "punct":
            if tok in "{[(":
                depth += 1
            elif tok in "}])":
                depth -= 1
                if depth == 0:
                    return m.end() - start
            elif tok == ";" and depth == 0:
                return i - start
        i = m.end()
    return n - start


# ── the sources, parsed ─────────────────────────────────────────────────────

def parse_i18n(src: str) -> Tuple[Dict[str, Dict[str, str]], List[str], List[str]]:
    """{locale: {key: text}}, the locales in LOCALES order, the validated ones."""
    names = dict(re.findall(r"\b([a-z]{2}):\s*([A-Z]{2})\b",
                            src[src.find("const DICTS"):src.find("const DICTS") + 400]))
    order = re.findall(r'\{\s*code:\s*"([a-z]{2})"', src)
    dicts: Dict[str, Dict[str, str]] = {}
    for code, var in names.items():
        try:
            d = const_literal(src, var)
            dicts[code] = {k: v for k, v in d.items() if isinstance(v, str)}
        except (LookupError, ValueError, IndexError):
            # fall back to the simple `"key": "value",` lines of the block
            m = re.search(rf"\bconst\s+{var}\b[^=]*=\s*\{{(.*?)\n\}};", src, re.S)
            dicts[code] = {k: js_unquote(f'"{v}"') for k, v in
                           re.findall(r'^\s*"([^"]+)":\s*"((?:\\.|[^"\\])*)",?\s*$', m.group(1) if m else "", re.M)}
    vm = re.search(r"VALIDATED[^=]*=\s*new Set<Locale>\(\[([^\]]*)\]", src)
    validated = re.findall(r'"([a-z]{2})"', vm.group(1)) if vm else ["en"]
    return dicts, [c for c in order if c in dicts] or sorted(dicts), validated


def parse_menus(src: str) -> Tuple[List[Dict[str, Any]], Dict[str, int]]:
    env: Dict[str, Any] = {"sep": {"kind": "sep"}}
    for m in re.finditer(r"\bconst\s+([A-Z_]+)\s*:\s*Platform\[\]\s*=\s*(\[[^\]]*\])", src):
        env[m.group(1)] = re.findall(r'"(\w+)"', m.group(2))
    # the helpers' signatures, checked rather than assumed
    if not re.search(r"const cmd = \(id: string, label: string, button: string, more", src):
        print("gen_commands: warning: the signature of cmd() in menu-table.ts changed", file=sys.stderr)
    if not re.search(r"const os = \(id: string, which: Predefined, label\?: string\)", src):
        print("gen_commands: warning: the signature of os() in menu-table.ts changed", file=sys.stderr)

    def build(v: Any) -> Any:
        if isinstance(v, Call):
            a = v["args"]
            if v["name"] == "cmd":
                more = a[3] if len(a) > 3 and isinstance(a[3], dict) else {}
                return {"kind": "cmd", "id": a[0], "label": a[1], "button": a[2], **more}
            if v["name"] == "os":
                return {"kind": "os", "id": a[0], "os": a[1], **({"label": a[2]} if len(a) > 2 and a[2] else {})}
            return {"kind": "unknown", "call": v["name"]}
        if isinstance(v, dict):
            out = {k: build(x) for k, x in v.items()}
            return out
        if isinstance(v, list):
            return [build(x) for x in v]
        return v

    menus = build(const_literal(src, "MENUS", env))
    lines = {}
    for m in re.finditer(r'\b(?:cmd|os)\("([^"]+)"', src):
        lines.setdefault(m.group(1), src.count("\n", 0, m.start()) + 1)
    for m in re.finditer(r'kind:\s*"sub",\s*id:\s*"([^"]+)"', src):
        lines.setdefault(m.group(1), src.count("\n", 0, m.start()) + 1)
    return menus, lines


def parse_keymap(src: str) -> Tuple[List[Dict[str, Any]], Dict[str, int]]:
    rows = const_literal(src, "KEYMAP")
    lines = {}
    for m in re.finditer(r'\{\s*id:\s*"([^"]+)"', src):
        lines.setdefault(m.group(1), src.count("\n", 0, m.start()) + 1)
    return [r for r in rows if isinstance(r, dict)], lines


# ── the host chain of run_command ───────────────────────────────────────────

def host_chain(tree: Tree) -> Dict[str, Any]:
    em_py = tree.read(SRC["em_py"])
    pys = tree.read(SRC["py_session"])
    main = tree.read(SRC["main"])
    mui = tree.read(SRC["menu_ui"])
    hook = re.search(r"command:\s*\((\w+)(?:\s*,\s*(\w+))?\)\s*=>\s*runCommand\(([^)]*)\)", main or "")
    find_row = re.search(r"function findRow\b.*?\n}\n", mui or "", re.S)
    cmd_only = bool(find_row and re.search(r'r\.kind\s*===\s*"cmd"\s*&&\s*r\.id\s*===\s*id', find_row.group()))
    steps = [
        ("em_py.run_command", SRC["em_py"], line_of(em_py, r"def run_command\(self, command_id"),
         "EMStudioApp.run_command asks the page: request kind \"command\" with id and slots"),
        ("py_session.case_command", SRC["py_session"], line_of(pys, r'case "command":'),
         "PySession answers the request through the page's host.command(id, slots); false -> error py.noCommand"),
        ("main.host_command", SRC["main"], line_of(main, r"command:\s*\(\w+(?:\s*,\s*\w+)?\)\s*=>\s*runCommand\("),
         "the page's host hook: command -> runCommand(id)"),
        ("menu_ui.runCommand", SRC["menu_ui"], line_of(mui, r"export function runCommand\("),
         "runCommand: plugin:<id>/<cmd> -> plugin invocation; otherwise findRow(id) and click the row's button"),
        ("menu_ui.findRow", SRC["menu_ui"], line_of(mui, r"function findRow\("),
         "findRow: only rows of kind \"cmd\" in MENUS (sub-menus walked)"),
    ]
    ok = all(s[2] for s in steps) and bool(hook)
    slots_forwarded = bool(hook and hook.group(2) and hook.group(2) in (hook.group(3) or ""))
    return {
        "complete": ok,
        "reachable_kinds": (["cmd"] if cmd_only else ["cmd", "?"]) if ok else [],
        "plugin_prefix": bool(mui and 'id.startsWith("plugin:")' in mui),
        "slots_forwarded": slots_forwarded,
        "button_disabled_fails": bool(mui and "b.disabled) return false" in mui),
        "steps": [{"key": k, "file": f, "line": ln, "what": w} for k, f, ln, w in steps],
    }


def library_chain() -> List[Dict[str, Any]]:
    out = []
    for path, pat, what in [
        (DEFAULT_EM_INIT, r"def run\(self, command_id", "em.app.commands.run -> host app run_command"),
        (DEFAULT_EM_HOST, r"def run_command\(self, command_id, \*\*slots\)", "NullHost: NotAvailable outside a host"),
    ]:
        text = path.read_text(encoding="utf-8") if path.is_file() else None
        out.append({"file": str(path.relative_to(REPO)) if path.is_file() else str(path),
                    "line": line_of(text, pat), "what": what})
    return out


def api_version(path: Path) -> str:
    if not path.is_file():
        return "unknown"
    m = re.search(r'^API_VERSION\s*=\s*["\']([^"\']+)["\']', path.read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else "unknown"


# ── the command list ────────────────────────────────────────────────────────

def keys_for(accel: str, mac: bool) -> str:
    parts = accel.split("+")
    key = parts.pop()
    if mac:
        sym = {"Shift": "⇧", "Alt": "⌥", "CmdOrCtrl": "⌘", "Ctrl": "⌃"}
        return "".join(sym[m] for m in ["Ctrl", "Alt", "Shift", "CmdOrCtrl"] if m in parts) + key.upper()
    word = {"Shift": "Shift", "Alt": "Alt", "CmdOrCtrl": "Ctrl", "Ctrl": "Ctrl"}
    return "+".join([word.get(m, m) for m in parts] + [key.upper()])


def surfaces_of(menu: Dict[str, Any], row: Dict[str, Any]) -> Dict[str, List[str]]:
    """Per platform, the surfaces drawing the row (menuRows' rules)."""
    out: Dict[str, List[str]] = {}
    only = row.get("only")
    for pf in PLATFORMS:
        # ``only: []`` (NOWHERE, MICRO-TIL003) = drawn on no platform: an empty
        # list is not «absent»
        if only is not None and pf not in only:
            continue
        surf = []
        for s in (menu.get("surfaces") or {}).get(pf) or []:
            if row["kind"] == "os" and s != "native":
                continue
            if menu.get("id") == "edit" and row["kind"] == "cmd" and s != "internal":
                continue
            surf.append(s)
        if surf:
            out[pf] = surf
    return out


def build_commands(tree: Tree) -> Dict[str, Any]:
    dicts, locales, validated = parse_i18n(tree.read(SRC["i18n"]) or "")
    menus, mlines = parse_menus(tree.read(SRC["menu_table"]) or "")
    keymap, klines = parse_keymap(tree.read(SRC["keymap"]) or "")
    chain = host_chain(tree)

    def tr(key: Optional[str]) -> Dict[str, str]:
        if not key:
            return {}
        return {lc: dicts[lc][key] for lc in locales if key in dicts.get(lc, {})}

    def tr_paths(keys: List[str]) -> Dict[str, str]:
        out = {}
        for lc in locales:
            words = [dicts.get(lc, {}).get(k) or dicts.get("en", {}).get(k) or k for k in keys]
            out[lc] = " ▸ ".join(words)
        return out

    commands: List[Dict[str, Any]] = []
    by_button: Dict[str, List[str]] = {}
    subs: List[Dict[str, Any]] = []

    def walk(menu: Dict[str, Any], rows: List[Any], path: List[str]) -> None:
        for row in rows:
            if not isinstance(row, dict):
                continue
            kind = row.get("kind")
            if kind == "sub":
                subs.append({"id": row["id"], "menu": menu["id"], "label": tr(row.get("label")),
                             "dynamic": row.get("dynamic"), "slot": row.get("slot"),
                             "line": mlines.get(row["id"])})
                walk(menu, row.get("rows") or [], path + [row.get("label", row["id"])])
                continue
            if kind not in ("cmd", "os"):
                continue
            reach = "yes" if kind in chain["reachable_kinds"] else ("unknown" if not chain["complete"] else "no")
            c: Dict[str, Any] = {
                "id": row["id"],
                "page": None,
                "kind": "menu" if kind == "cmd" else "os",
                "command_id": row["id"] if kind == "cmd" else None,
                "label_key": row.get("label"),
                "label": tr(row.get("label")) if row.get("label") else {"en": row.get("os", row["id"])},
                "title_key": row.get("title"),
                "title": tr(row.get("title")),
                "button": row.get("button"),
                "os_item": row.get("os"),
                "menu": menu["id"],
                "menu_path": tr_paths(path + [row["label"]] if row.get("label") else path),
                "surfaces": surfaces_of(menu, row),
                "accel": row.get("accel"),
                "accel_not_on_web": bool(row.get("accelNotOnWeb")),
                "shortcut": {"mac": keys_for(row["accel"], True), "pc": keys_for(row["accel"], False)}
                if row.get("accel") else None,
                "keymap": None,
                "reachable_from_python": reach,
                "writes_graph": "unknown",
                "slots": [],
                "source": {"file": SRC["menu_table"], "line": mlines.get(row["id"])},
            }
            if not row.get("label") and kind == "os":
                c["label"] = {}
            if row.get("button"):
                by_button.setdefault(row["button"], []).append(row["id"])
            commands.append(c)

    for menu in menus:
        walk(menu, menu.get("rows") or [], [menu.get("label", menu["id"])])

    for c in commands:
        if c["button"]:
            c["same_button_as"] = [i for i in by_button[c["button"]] if i != c["id"]]

    by_id = {c["id"]: c for c in commands if c["kind"] == "menu"}
    for row in keymap:
        kid, keys = row.get("id"), str(row.get("keys", ""))
        gesture = keys.startswith("@")
        km = {"id": kid, "keys": keys if not gesture else None,
              "gesture_key": keys[1:] if gesture else None,
              "gesture": tr(keys[1:]) if gesture else {},
              "scope": row.get("scope"), "label_key": f"keys.{kid}", "label": tr(f"keys.{kid}"),
              "source": {"file": SRC["keymap"], "line": klines.get(kid)}}
        if kid in by_id:                       # a menu command's key, written in the key map too
            by_id[kid]["keymap"] = km
            continue
        commands.append({
            "id": f"keymap:{kid}",
            "page": None,
            "kind": "gesture" if gesture else "shortcut",
            "command_id": None,
            "label_key": f"keys.{kid}",
            "label": tr(f"keys.{kid}"),
            "title_key": None,
            "title": {},
            "button": None,
            "menu": None,
            "menu_path": {},
            "surfaces": {},
            "accel": None,
            "shortcut": None,
            "keymap": km,
            "reachable_from_python": "no" if chain["complete"] else "unknown",
            "writes_graph": "unknown",
            "slots": [],
            "source": km["source"],
        })

    # file-safe, case-insensitively unique page names
    taken: Dict[str, int] = {}
    for c in commands:
        base = re.sub(r"[^A-Za-z0-9_.-]+", "-", c["id"].replace("keymap:", "keymap-")).strip("-") or "command"
        name, n = base, 1
        while name.lower() in taken:
            n += 1
            name = f"{base}-{n}"
        taken[name.lower()] = 1
        c["page"] = name

    return {"commands": commands, "submenus": subs, "chain": chain, "locales": locales,
            "validated_locales": validated}


# ── RST ─────────────────────────────────────────────────────────────────────

_RST_SPECIAL = re.compile(r"([\\`*_|\[\]<>])")


def esc(text: Any) -> str:
    """Inline text safe for RST: markup characters escaped, a leading list marker defused."""
    s = " ".join(str(text if text is not None else "").split())
    s = _RST_SPECIAL.sub(r"\\\1", s)
    if re.match(r"^([-+•]|\d+[.)]|#\.)(\s|$)", s):
        s = "\\" + s
    return s


def lit(text: Any) -> str:
    s = " ".join(str(text).split())
    if not s:
        return "—"
    if "`" in s:
        return esc(s)
    return f"``{s}``"


def heading(text: str, ch: str) -> List[str]:
    return [text, ch * max(len(text), 4), ""]


def table(rows: List[List[str]], header: Optional[List[str]] = None, widths: Optional[List[int]] = None,
          stub: bool = False) -> List[str]:
    out = [".. list-table::"]
    if header:
        out.append("   :header-rows: 1")
    if widths:
        out.append("   :widths: " + " ".join(str(w) for w in widths))
    if stub:
        out.append("   :stub-columns: 1")
    out.append("")
    for row in ([header] if header else []) + rows:
        for j, cell in enumerate(row):
            lines = (cell or "—").split("\n")
            out.append(("   * - " if j == 0 else "     - ") + lines[0])
            out.extend("       " + ln for ln in lines[1:])
    out.append("")
    return out


def shortcut_text(c: Dict[str, Any]) -> str:
    bits = []
    if c.get("shortcut"):
        s = c["shortcut"]
        bits.append(f"{lit(s['mac'])} (macOS) / {lit(s['pc'])} (Windows, Linux)"
                    + (" — not on the web, the browser keeps it" if c.get("accel_not_on_web") else ""))
    km = c.get("keymap")
    if km:
        if km.get("keys"):
            k = lit(km["keys"])
            if not bits or km["keys"] not in (c.get("shortcut") or {}).values():
                bits.append(f"{k} (key map, scope ``{km['scope']}``)")
        elif km.get("gesture"):
            g = km["gesture"]
            bits.append(f"{esc(g.get('en', km['gesture_key']))} (gesture, scope ``{km['scope']}``)")
    return "; ".join(bits)


def short_shortcut(c: Dict[str, Any]) -> str:
    if c.get("shortcut"):
        return lit(c["shortcut"]["mac"])
    km = c.get("keymap") or {}
    if km.get("keys"):
        return lit(km["keys"])
    if km.get("gesture"):
        return esc(km["gesture"].get("en", ""))
    return ""


def where_text(c: Dict[str, Any]) -> str:
    if not c.get("surfaces"):
        return ""
    by: Dict[str, List[str]] = {}
    for pf, surf in c["surfaces"].items():
        for s in surf:
            by.setdefault(s, []).append(PLATFORM_NAMES[pf])
    names = {"internal": "the page's menu bar", "native": "the system menu bar"}
    return "; ".join(f"{names[s]}: {', '.join(pfs)}" for s, pfs in by.items())


def gen_line(meta: Dict[str, Any]) -> str:
    return f"*Generated from EMStudio {esc(meta['emstudio_sha'])} for em API {esc(meta['em_api_version'])}.*"


def page_for(c: Dict[str, Any], data: Dict[str, Any], meta: Dict[str, Any]) -> str:
    chain = data["chain"]
    steps = {s["key"]: s for s in chain["steps"]}
    lab = c["label"]
    out = [MARKER, "", f".. _emstudio-command-{c['page']}:", ""]
    out += heading(c["id"], "=")
    out += [gen_line(meta), ""]

    kinds = {"menu": "Menu command", "os": "Item drawn by the operating system (no page button)",
             "shortcut": "Key of the key map (no command id)", "gesture": "Gesture of the key map (no command id)"}
    kind_text = kinds[c["kind"]]
    if c.get("button"):
        kind_text += f" — presses the page button {lit(c['button'])}"
    if c.get("os_item"):
        kind_text += f" — OS item {lit(c['os_item'])}"
    reach = c["reachable_from_python"]
    reach_text = {"yes": f"yes — ``em.app.commands.run(\"{c['command_id']}\")``" if c.get("command_id") else "yes",
                  "no": "no", "unknown": "unknown (the host chain was not found in the sources)"}[reach]
    rows = [
        ["Id", lit(c["id"])],
        ["Label (en)", esc(lab.get("en", "")) or "—"],
        ["Label (it)", esc(lab.get("it", "")) or "—"],
        ["Kind", kind_text],
        ["Reachable from Python", reach_text],
        ["Writes to the graph", "not declared"],
    ]
    if c.get("menu_path") and c.get("surfaces"):
        rows.append(["Menu path (en)", esc(c["menu_path"].get("en", ""))])
        rows.append(["Menu path (it)", esc(c["menu_path"].get("it", ""))])
        rows.append(["Drawn in", esc(where_text(c)) or "—"])
    elif c["kind"] == "menu":
        # MICRO-TIL003 · a command kept without an item (``only: []``): its
        # button waits hidden in the page, the command id still runs it
        rows.append(["Drawn in", "no menu — the command is kept for Python and the keys; "
                                 "its item was replaced by another entry"])
    rows.append(["Shortcut", shortcut_text(c) or "none"])
    if c.get("same_button_as"):
        rows.append(["Same button as", ", ".join(f":doc:`{i} <{i}>`" for i in c["same_button_as"])])
    src = c["source"]
    rows.append(["Defined in", lit(f"{src['file']}:{src['line']}") if src.get("line") else lit(src["file"])])
    out += table(rows, widths=[25, 75], stub=True)

    if reach != "yes":
        out += [".. admonition:: Not yet available from Python", "   :class: warning", ""]
        if c["kind"] == "os":
            out.append("   An item the operating system draws in the macOS menu bar: it has no page button, "
                       "and ``runCommand`` only finds rows of kind ``cmd`` "
                       f"(``{steps['menu_ui.findRow']['file']}:{steps['menu_ui.findRow']['line']}``), so "
                       "``em.app.commands.run`` raises ``em.NotAvailable``.")
        elif c["kind"] in ("shortcut", "gesture"):
            out.append("   A key or gesture handled directly by the page, not a row of the command table "
                       f"(``{SRC['menu_table']}``): ``em.app.commands.run`` has no id to reach it.")
        else:
            out.append("   The host chain of ``run_command`` could not be confirmed in the EMStudio sources.")
        out.append("")

    out += heading("What it does", "-")
    said = False
    if c.get("title"):
        for lc in ("en", "it"):
            if c["title"].get(lc):
                out += [f"**{lc}** — {esc(c['title'][lc])}", ""]
                said = True
    km = c.get("keymap") or {}
    if km.get("label") and c["kind"] == "menu":
        for lc in ("en", "it"):
            if km["label"].get(lc):
                out += [f"**{lc}** (key map) — {esc(km['label'][lc])}", ""]
                said = True
    if not said:
        if lab.get("en") or lab.get("it"):
            out += ["No tooltip or description string in ``i18n.ts``; the label is all the UI says.", ""]
        else:
            out += ["No label, tooltip or description string in ``i18n.ts`` (the operating system names it).", ""]

    others = [lc for lc in data["locales"] if lc not in ("en", "it") and lab.get(lc)]
    if others:
        out += heading("Label in the other languages", "-")
        out += ["AI drafts, not yet validated by a person (see ``isValidated`` in ``i18n.ts``)." , ""]
        out += table([[lit(lc), esc(lab[lc])] for lc in others], header=["Locale", "Label"], widths=[15, 85])

    out += heading("Slots", "-")
    if c["kind"] == "menu":
        out.append("None declared: the command table (``CommandRow`` in ``menu-table.ts``) declares no slots, "
                   "types or defaults.")
        if not chain["slots_forwarded"]:
            h = steps["main.host_command"]
            out.append(f"Keyword slots passed to ``em.app.commands.run`` reach the page but are dropped by the "
                       f"host hook (``{h['file']}:{h['line']}``), which calls ``runCommand(id)`` only.")
    else:
        out.append("None.")
    out.append("")

    if reach == "yes":
        out += heading("From Python", "-")
        out += [".. code-block:: python", "", "   from s3dgraphy import em", "",
                f"   em.app.commands.run(\"{c['command_id']}\")", ""]
        notes = ["The page presses the command's button, as a click would: whatever dialog the command opens, "
                 "opens."]
        if chain["button_disabled_fails"]:
            notes.append("If the button is disabled at that moment (or the id is unknown) the call raises "
                         "``em.NotAvailable`` (``py.noCommand``).")
        notes.append("Outside EMStudio (no host) the call raises ``em.NotAvailable``.")
        out += [" ".join(notes), ""]
    return "\n".join(out).rstrip() + "\n"


def index_page(data: Dict[str, Any], meta: Dict[str, Any]) -> str:
    cmds = data["commands"]
    chain = data["chain"]
    out = [MARKER, "", ".. _emstudio-commands:", ""]
    out += heading("EMStudio commands", "=")
    out += [gen_line(meta), ""]
    n_menu = sum(1 for c in cmds if c["kind"] == "menu")
    n_yes = sum(1 for c in cmds if c["reachable_from_python"] == "yes")
    out += [f"Every command of EMStudio's menus ({n_menu} rows of the command table, {n_yes} reachable from "
            "Python), the items the operating system draws in the macOS menu bar, and the keys and gestures "
            "of the key map. ``em.app.commands.run(command_id, **slots)`` reaches a command by the id in the "
            "first column.", ""]
    out += heading("How ``run_command`` reaches the page", "-")
    for s in library_chain():
        out.append(f"#. ``{s['file']}:{s['line']}`` — {esc(s['what'])}")
    for s in chain["steps"]:
        out.append(f"#. ``{s['file']}:{s['line']}`` — {esc(s['what'])}")
    out.append("")
    extra = []
    if chain["plugin_prefix"]:
        extra.append("Plugin commands are reachable too, as ``plugin:<plugin>/<command>`` (registered at run "
                     "time, not listed here; see ``em.plugins``).")
    if not chain["slots_forwarded"]:
        extra.append("Slots are accepted by the API but not forwarded to the command by the page.")
    extra.append("No command declares whether it writes to the graph: the column says ``unknown``.")
    out += [" ".join(extra), ""]

    header = ["Id", "Label (en)", "Label (it)", "Menu path", "Shortcut", "Python", "Writes graph"]

    def rows_of(kind: str) -> List[List[str]]:
        rows = []
        for c in cmds:
            if c["kind"] != kind:
                continue
            rows.append([f":doc:`{c['id']} <{c['page']}>`",
                         esc(c["label"].get("en", "")) or (f"OS: {lit(c['os_item'])}" if c.get("os_item") else ""),
                         esc(c["label"].get("it", "")),
                         esc(c["menu_path"].get("en", "")), short_shortcut(c),
                         c["reachable_from_python"], c["writes_graph"]])
        return rows

    sections = [("menu", "Menu commands"), ("os", "Operating-system menu items (macOS menu bar)"),
                ("shortcut", "Keys of the key map without a command"),
                ("gesture", "Gestures of the key map")]
    for kind, title in sections:
        rows = rows_of(kind)
        if not rows:
            continue
        out += heading(f"{title} ({len(rows)})", "-")
        out += table(rows, header=header, widths=[16, 18, 18, 22, 12, 7, 7])
    dyn = [s for s in data["submenus"] if s.get("dynamic") or s.get("slot")]
    if dyn:
        out += heading("Sub-menus filled at run time", "-")
        for s in dyn:
            what = (f"dynamic ({s['dynamic']})" if s.get("dynamic") else "") + \
                   (f"plugin slot ``{s['slot']}``" if s.get("slot") else "")
            out.append(f"* ``{s['id']}`` — {esc(s['label'].get('en', ''))}: {what}")
        out.append("")
    out += [".. toctree::", "   :hidden:", "   :maxdepth: 1", ""]
    out += [f"   {c['page']}" for c in sorted(cmds, key=lambda c: c["page"].lower())]
    return "\n".join(out).rstrip() + "\n"


# ── main ────────────────────────────────────────────────────────────────────

def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--emstudio", default=os.environ.get("EMSTUDIO_SRC", "~/Documents/GitHub/EMStudio"),
                    help="EMStudio checkout (default: $EMSTUDIO_SRC or ~/Documents/GitHub/EMStudio)")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="output folder (default: docs-api/reference/commands)")
    ap.add_argument("--worktree", action="store_true", help="read EMStudio's files on disk instead of at HEAD")
    args = ap.parse_args(argv)

    root = Path(os.path.expanduser(args.emstudio)).resolve()
    if not (root / SRC["menu_table"]).is_file():
        print(f"gen_commands: EMStudio not found at {root} — the committed pages are left as they are.")
        return 0
    tree = Tree(root, args.worktree)
    missing = [rel for rel in (SRC["menu_table"], SRC["keymap"], SRC["i18n"]) if tree.read(rel) is None]
    if missing:
        print(f"gen_commands: {', '.join(missing)} not readable in {root} — the committed pages are left as they are.")
        return 0

    data = build_commands(tree)
    meta = {"emstudio_sha": tree.sha or "unknown",
            "emstudio_read": "HEAD" if tree.at_head else "worktree",
            "em_api_version": api_version(DEFAULT_EM_INIT)}
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    written = set()
    for c in data["commands"]:
        p = out_dir / f"{c['page']}.rst"
        p.write_text(page_for(c, data, meta), encoding="utf-8")
        written.add(p.name)
    (out_dir / "index.rst").write_text(index_page(data, meta), encoding="utf-8")
    written.add("index.rst")
    for old in out_dir.glob("*.rst"):                # pages of commands that are gone
        if old.name not in written and old.read_text(encoding="utf-8").startswith(MARKER):
            old.unlink()

    payload = {"generated_from": meta, "sources": SRC, "library_chain": library_chain(),
               "host_chain": data["chain"], "locales": data["locales"],
               "validated_locales": data["validated_locales"],
               "submenus": data["submenus"], "commands": data["commands"]}
    (out_dir / "commands.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    cmds = data["commands"]
    gap = [c["id"] for c in cmds if c["kind"] in ("menu", "os") and c["reachable_from_python"] != "yes"]
    print(f"gen_commands: EMStudio {meta['emstudio_sha']} ({meta['emstudio_read']}), em API {meta['em_api_version']}: "
          f"{sum(1 for c in cmds if c['kind'] == 'menu')} menu commands, "
          f"{sum(1 for c in cmds if c['reachable_from_python'] == 'yes')} reachable from Python; "
          f"{len(gap)} menu items not reachable; {len(cmds)} pages -> {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
