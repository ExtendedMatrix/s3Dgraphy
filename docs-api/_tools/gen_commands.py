#!/usr/bin/env python3
"""Reference of the EMStudio commands, as seen from ``em.app.commands.run``.

Reads EMStudio's TypeScript sources (light parsing, not a TS compiler):

* ``frontend/src/menu-table.ts`` -- the one table of menu commands (``MENUS``);
* ``frontend/src/keymap.ts``     -- every key and gesture (``KEYMAP``);
* ``frontend/src/i18n.ts``       -- the labels, one dictionary per locale;
* the host chain of ``run_command`` (``tools/em_py.py`` -> ``py-session.ts`` ->
  ``main.ts`` -> ``menu-ui.ts``), to decide what Python can reach;

and writes ``commands.json`` plus one RST page per command and an ``index.rst``.

By default the EMStudio sources are read at ``HEAD`` (``git show HEAD:<path>``),
so the short sha printed on every page is exactly what was read; ``--worktree``
reads the files on disk instead. Without an EMStudio tree the script prints a
notice and exits 0, leaving the committed pages untouched (Read the Docs has no
EMStudio checkout and uses them as they are).

Stdlib only, Python >= 3.9.

    python docs-api/_tools/gen_commands.py [--emstudio PATH] [--out DIR] [--worktree]
"""
