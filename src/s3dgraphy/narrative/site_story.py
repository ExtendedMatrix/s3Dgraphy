"""The `site_story` template — the first one, derived from PortaMarina.

Structure (narrative-vision-spec §3):

    1. Presentazione        canonical   project prose + every source
    2. Dove si trova        canonical   the geographic placement
    3. one chapter per epoch            the units of that lane, each with
                                        "how I know it" beside it
    4. one chapter per activity         what was DONE, and the units it was
                                        done to, each with its evidence

The chapters that carry the argument are 3 and 4. A chapter is a lane; inside
it, each unit sits next to its evidence chain — the paradata **in** the story,
not in an appendix. Reading the chapters in order is reading the site through
time, which is what makes multitemporal stratigraphy legible to someone who is
not holding the matrix in their head.

The template writes **no content**. Where prose belongs it leaves a bracketed
placeholder, because a sentence invented here would enter the record under the
author's name.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from ..nodes.narrative_node import NarrativeNode
from .registry import register_template

#: What this template WRITES, in the two validated languages.
#:
#: The scaffolder's output is CONTENT: chapter titles and placeholder prose become
#: fields of the em.json, and after that they belong to the author. So they are
#: generated in the language asked for at build time — `lang="en"` by default,
#: matching the decision the UI made on 21 Aug 2026 (English is the reference, and
#: nothing is given a language it was not asked for) — and never rewritten
#: afterwards: re-translating somebody's chapter title because the interface
#: changed language would be an edit nobody asked for.
#:
#: `en` is the reference and the fallback. A language the table does not carry
#: falls back to it rather than mixing two languages in one document.
_PHRASES = {
    "en": {
        "placeholder": "[to be written: {what}]",
        "story_of": "{site} — the story of the site",
        "draft_note": ("Draft generated by the site_story template; "
                       "the prose is to be written."),
        "presentation": "Presentation",
        "project_intro": "a presentation of the project «{name}»",
        "site_intro": "a presentation of {site}",
        "how_to_read": ("how this account is to be read and which sources it "
                        "rests on"),
        "where": "Where it is",
        "geo_context": "the geographical context",
        "site_unplaced": ("the site's position — the graph carries only the "
                          "georeferencing of the 3D scene, which does not say "
                          "where the site is: place the site"),
        "epoch_what": "what happens in «{name}»",
        "activity_what": "the activity «{name}»: what was done",
    },
    "it": {
        "placeholder": "[da scrivere: {what}]",
        "story_of": "{site} — la storia del sito",
        "draft_note": ("Bozza generata dal template site_story; "
                       "la prosa è da scrivere."),
        "presentation": "Presentazione",
        "project_intro": "presentazione del progetto «{name}»",
        "site_intro": "presentazione di {site}",
        "how_to_read": "come si legge questo racconto e su quali fonti si appoggia",
        "where": "Dove si trova",
        "geo_context": "il contesto geografico",
        "site_unplaced": ("la posizione del sito — il grafo ha solo la "
                          "georeferenziazione della scena 3D, che non dice "
                          "dove si trova il sito: il sito va posizionato"),
        "epoch_what": "che cosa accade in «{name}»",
        "activity_what": "l'attività «{name}»: che cosa è stato fatto",
    },
}

#: The language a caller gets when it asks for none. English, like the UI.
DEFAULT_LANG = "en"


def phrase(lang: Optional[str], key: str, **vars: Any) -> str:
    """One of the strings above, in `lang`, falling back to English.

    A function and not a constant for the reason a constant would hide: this
    template is imported once and used for many graphs, in more than one
    language, and a module-level string would freeze whichever came first.
    """
    table = _PHRASES.get((lang or DEFAULT_LANG)[:2].lower(),
                         _PHRASES[DEFAULT_LANG])
    raw = table.get(key) or _PHRASES[DEFAULT_LANG].get(key, key)
    return raw.format(**vars) if vars else raw


#: Placeholder prose in the DEFAULT language, bracketed so it is unmistakable on
#: the page and greppable in the file — an author must be able to find everything
#: still unwritten. Kept because it was public; anything that has a language to
#: hand should call `phrase(lang, "placeholder", what=…)` instead, or it will write
#: English into an Italian document.
PLACEHOLDER = _PHRASES[DEFAULT_LANG]["placeholder"]

#: The lane chapter shows a unit through its `us` view; where the unit has a
#: property justified by an evidence chain, a `paradata` embed goes beside it.
_EVIDENCE_EDGE = "has_data_provenance"
_PROPERTY_EDGE = "has_property"

#: What counts as "a source" in the presentation chapter. DocumentNode covers
#: its subclasses too, which is the point of matching on the class.
from ..nodes.document_node import DocumentNode as _SourceClass
from ..nodes.epoch_node import EpochNode as _EpochClass
from ..nodes.geo_position_node import GeoPositionNode as _GeoClass
from ..nodes.graph_node import GraphNode as _GraphClass
from ..nodes.group_node import ActivityNodeGroup as _ActivityClass
from ..nodes.project_node import ProjectNode as _ProjectClass

#: Units belong to a lane through these edges (first-epoch attribution, and
#: survival into later epochs).
_EPOCH_EDGES = ("has_first_epoch", "survive_in_epoch")


def _nodes(graph, node_class) -> List[Any]:
    """Nodes of a class, not of a node_type STRING.

    The two are not interchangeable and the difference bites: `EpochNode` has
    node_type `"EpochNode"` while `DocumentNode` has `"document"`. Matching on
    the class also picks up subclasses, which is what "every source" or "every
    unit" means.
    """
    return [n for n in graph.nodes if isinstance(n, node_class)]


def _out(graph, node_id: str, edge_type: str) -> List[str]:
    return [e.edge_target for e in graph.edges
            if e.edge_source == node_id and e.edge_type == edge_type]


def _in(graph, node_id: str, edge_type: str) -> List[str]:
    return [e.edge_source for e in graph.edges
            if e.edge_target == node_id and e.edge_type == edge_type]


def _units_of_epoch(graph, epoch_id: str) -> List[Any]:
    """The stratigraphic units attributed to a lane, ordered by stratigraphy.

    `is_after` is the sequence: a unit that is after another comes later in the
    deposit, so the chapter reads oldest-first — the order in which the site was
    built, which is the order a story wants.
    """
    ids = set()
    for edge_type in _EPOCH_EDGES:
        ids.update(_in(graph, epoch_id, edge_type))
    units = [n for n in graph.nodes if n.node_id in ids and _is_stratigraphic(n)]
    return _topological_by_is_after(graph, units)


def _is_stratigraphic(node) -> bool:
    from ..nodes.stratigraphic_node import StratigraphicNode
    return isinstance(node, StratigraphicNode)


def _topological_by_is_after(graph, units: List[Any]) -> List[Any]:
    """Order units so that `A is_after B` puts B first — oldest at the top.

    A plain depth-first walk over `is_after`, tolerant of the cycles a real
    graph sometimes has: a unit already being visited is simply not recursed
    into, so a cyclic dataset still produces an order instead of an exception.
    Ties keep the graph's own order, which makes the output reproducible.
    """
    index = {u.node_id: u for u in units}
    ordered: List[Any] = []
    seen: set = set()
    visiting: set = set()

    def visit(uid: str) -> None:
        if uid in seen or uid in visiting:
            return
        visiting.add(uid)
        for older in _out(graph, uid, "is_after"):
            if older in index:
                visit(older)
        visiting.discard(uid)
        seen.add(uid)
        ordered.append(index[uid])

    for unit in units:
        visit(unit.node_id)
    return ordered


def _evidence_for(graph, unit_id: str) -> List[str]:
    """The property nodes of a unit that are backed by an evidence chain.

    Only those: a property nobody justified has no "how I know it" to show, and
    an embed pointing at nothing would be furniture.
    """
    out = []
    for prop_id in _out(graph, unit_id, _PROPERTY_EDGE):
        if _out(graph, prop_id, _EVIDENCE_EDGE):
            out.append(prop_id)
    return out


def _epoch_sort_key(epoch) -> tuple:
    """Chronological: oldest chapter first. An epoch with no start time sorts
    last rather than crashing the sort — a graph mid-authoring is normal."""
    start = getattr(epoch, "start_time", None)
    return (0, float(start)) if isinstance(start, (int, float)) \
        else (1, 0.0)


@register_template("site_story")
def build_site_story(graph, *, node_id: str = None, title: str = None,
                     lang: Optional[str] = None, **opts) -> NarrativeNode:
    """Lay out the story of a site as chapters over its lanes.

    Returns a fresh draft. To regenerate over an existing narrative without
    losing the author's work, go through
    :func:`~s3dgraphy.narrative.registry.build_narrative` with ``existing=``.
    """
    graph_name = _text(getattr(graph, "name", None)) or graph.graph_id
    narrative = NarrativeNode(
        node_id=node_id or f"narrative_{graph.graph_id}",
        name=title or phrase(lang, "story_of", site=graph_name),
        description=phrase(lang, "draft_note"),
        lang=lang,
        template_id="site_story",
    )

    _presentation_chapter(graph, narrative, graph_name, lang)
    _geo_chapter(graph, narrative, lang)
    _epoch_chapters(graph, narrative, lang)
    _activity_chapter(graph, narrative, lang)
    return narrative


# ── 1. Presentazione ─────────────────────────────────────────────────────────

def _presentation_chapter(graph, narrative, graph_name, lang=None) -> None:
    chapter = narrative.add_chapter(phrase(lang, "presentation"), canonical=True)
    projects = _nodes(graph, _ProjectClass)
    if projects:
        project = projects[0]
        desc = (getattr(project, "description", "") or "").strip()
        if desc:
            chapter.add_prose(desc)
        else:
            chapter.add_prose(phrase(
                lang, "placeholder",
                what=phrase(lang, "project_intro", name=project.name)))
    else:
        chapter.add_prose(phrase(
            lang, "placeholder",
            what=phrase(lang, "site_intro", site=graph_name)))

    # One embed per source, not a table. A table would list them; an embed
    # SHOWS each one, with its criticism, which is what a reader of a
    # reconstruction needs — and it keeps every source individually
    # referenced, so "which narratives rest on this source" stays answerable.
    # A prompt is a source OF THE NARRATIVE, not of the reconstruction: listing
    # it beside Maiuri's survey would be a category error. Since N7 a prompt is
    # an ExtractorNode, so it cannot reach this list at all — but graphs written
    # before N7 still hold prompts as documents, and dropping the guard would
    # make the machine's instructions reappear among the sources on reload.
    prompts = {ref for n in _nodes(graph, NarrativeNode)
               for ref in n.prompt_refs()}
    sources = [s for s in _nodes(graph, _SourceClass)
               if s.node_id not in prompts]
    if sources:
        chapter.add_prose(phrase(lang, "placeholder",
                                 what=phrase(lang, "how_to_read")))
        for source in sorted(sources, key=lambda n: str(n.name or n.node_id)):
            chapter.add_embed(source.node_id, "source")


# ── 2. Dove si trova ─────────────────────────────────────────────────────────

def _geo_chapter(graph, narrative, lang=None) -> None:
    """«Where it is» is born from the SITE, not from the 3D scene.

    The site is `GraphNode.data.site_position` (GEO1) — a place on Earth, the one
    `study._spatial_of` catalogues and `bake._map_block` draws. The
    GeoPositionNode is something else: the ANCHOR of the 3D scene, whose shift
    is an offset for the models, not where the dot goes. The chapter used to be
    born from the shift and to point the map at the geo node; a site placed only
    through `site_position` got no chapter at all, and a shifted scene got a map
    of its origin.

    Three cases:

    * **site_position** → the chapter, a placeholder, and the map embed on the
      GRAPH node;
    * **only a shift** → the chapter is born anyway (the graph IS somewhere, the
      scene says so), but its prose says the site is still to be placed, and
      the map points at the graph node, which bakes as "position not recorded".
      No point is derived from the shift: that would be the 3D offset passed off
      as the site. If the graph has no GraphNode there is nothing honest to point
      at, and the chapter carries the prose alone;
    * **neither** → no chapter. Inventing coordinates for a site would be the
      worst kind of plausible.
    """
    site_node = _site_node(graph)
    placed = [g for g in _nodes(graph, _GeoClass) if _has_coordinates(g)]
    if site_node is None and not placed:
        return
    chapter = narrative.add_chapter(phrase(lang, "where"), canonical=True)
    if site_node is not None:
        chapter.add_prose(phrase(lang, "placeholder",
                                 what=phrase(lang, "geo_context")))
        chapter.add_embed(site_node.node_id, "map")
        return
    chapter.add_prose(phrase(lang, "placeholder",
                             what=phrase(lang, "site_unplaced")))
    graphs = _nodes(graph, _GraphClass)
    if graphs:
        chapter.add_embed(graphs[0].node_id, "map")


def _site_node(graph):
    """The GraphNode that carries a usable `site_position`, or None."""
    for node in _nodes(graph, _GraphClass):
        if site_position_of(node) is not None:
            return node
    return None


def site_position_of(node) -> Optional[Dict[str, float]]:
    """`{"lat", "lon"}` from a node's `site_position`, or None when it has none
    or it does not parse. The same test `study._spatial_of` applies."""
    data = getattr(node, "data", None)
    site = data.get("site_position") if isinstance(data, dict) else None
    if not isinstance(site, dict):
        return None
    try:
        return {"lat": float(site["lat"]), "lon": float(site["lon"])}
    except (KeyError, TypeError, ValueError):
        return None


def _has_coordinates(geo) -> bool:
    data = getattr(geo, "data", {}) or {}
    x, y = data.get("shift_x"), data.get("shift_y")
    return bool(x or y)


# ── 3. Un capitolo per epoca ─────────────────────────────────────────────────

def _epoch_chapters(graph, narrative, lang=None) -> None:
    for epoch in sorted(_nodes(graph, _EpochClass), key=_epoch_sort_key):
        units = _units_of_epoch(graph, epoch.node_id)
        if not units:
            continue  # an empty lane has no story yet
        chapter = narrative.add_chapter(str(epoch.name), anchor=epoch.node_id)
        chapter.add_prose(phrase(
            lang, "placeholder",
            what=phrase(lang, "epoch_what", name=epoch.name)))
        for unit in units:
            chapter.add_embed(unit.node_id, "us")
            # "come lo so": the evidence beside the claim, not in an appendix
            for prop_id in _evidence_for(graph, unit.node_id):
                chapter.add_embed(prop_id, "paradata")


# ── 4. Il cantiere ───────────────────────────────────────────────────────────

def _activity_chapter(graph, narrative, lang=None) -> None:
    """The actions performed in antiquity, one chapter per activity.

    E.D., 2 Aug 2026: the **ActivityNodeGroup IS the activity** — «costruzione
    della torre» — and its **actions** are the units it contains. No new "event"
    type: the language already has the right node, and adding one would have
    split a concept that is whole.

    So each activity gets its own chapter, anchored to it exactly as an epoch
    chapter is anchored to its lane. That is what makes the multitemporal
    reading work: the epochs tell you WHEN, the activities tell you WHAT WAS
    DONE, and both are lanes of the same graph.

    If the activity carries a narrative account of its own
    (`ActivityNodeGroup.narrative`), that prose opens the chapter; otherwise a
    placeholder does. Nothing is invented either way.
    """
    activities = _nodes(graph, _ActivityClass)
    if not activities:
        return
    for activity in activities:
        chapter = narrative.add_chapter(str(activity.name),
                                        anchor=activity.node_id)
        account = getattr(activity, "narrative", "") or ""
        if account.strip():
            chapter.add_prose(account)
        else:
            chapter.add_prose(phrase(
                lang, "placeholder",
                what=phrase(lang, "activity_what", name=activity.name)))
        # the actions: the units this activity contains, in stratigraphic order
        members = [graph.find_node_by_id(mid)
                   for mid in _in(graph, activity.node_id, "is_in_activity")]
        units = [m for m in members if m is not None and _is_stratigraphic(m)]
        for unit in _topological_by_is_after(graph, units):
            chapter.add_embed(unit.node_id, "us")
            for prop_id in _evidence_for(graph, unit.node_id):
                chapter.add_embed(prop_id, "paradata")


def _text(value) -> Optional[str]:
    if isinstance(value, dict):
        return value.get("default") or next(iter(value.values()), None)
    return value if isinstance(value, str) else None
